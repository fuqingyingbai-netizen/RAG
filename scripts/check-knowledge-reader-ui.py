"""Browser scenarios for the integrated reader, using real server-generated artifacts.

Run through check-knowledge-notes-ui.py --reader-regression. Format artifacts are
generated by the real backend in an isolated PostgreSQL restore, then transported
locally for deterministic browser decoding. Upload/delete routes use real SQLite APIs.
"""
import json
import re
from urllib.parse import urlparse, parse_qs

import httpx
from playwright.sync_api import expect
from sqlalchemy import select


def configure(state, args, patch):
    from test_company_workspace import project, upload
    from company_catalog import CompanyDocument
    import company_knowledge as kb
    async def isolated_cloud(client,cfg,path,body):
        assert path=='/api/v1/indices/rag/index/delete_file',path
        return {'success':True}
    patch.setattr(kb,'cloud_rpc',isolated_cloud)
    library = project(state, '连续上传与双击验证')
    folder = state.client.post('/company-knowledge/projects/'+library['id']+'/folders', json={'name':'子目录验证'}).json()
    formats = json.loads((args.formats_dir/'matrix.json').read_text()) if args.formats_dir else []
    rows = {}
    if formats:
        directory = project(state, '19 类格式实际显示验证')
        for item in formats:
            response = upload(state, b'fixture', name='matrix-'+item['format']+'.txt', project_id=directory['id'],description='Synthetic browser decode verification')
            assert response.status_code==202,(item['format'],response.text)
            result = response.json()
            with state.db() as db:
                doc=db.get(CompanyDocument,result['id']);doc.state='ready';doc.cloud_id='matrix-'+item['format'];doc.format=item['format'];doc.title='matrix.'+item['format'].lower();db.commit()
            rows[result['id']]=item
    def response(path):
        parsed=urlparse(path)
        match=re.fullmatch('/company-knowledge/documents/([^/]+)/(original|page|preview|outline|thumbnail)', parsed.path)
        if not match:return None
        doc_id, action=match.groups()
        if action=='preview':
            page=int(parse_qs(parsed.query).get('page',['1'])[0])
            refs=[{'id':i,'document_id':'matrix','title':'解析测试','text':('末 页 关 键 词，OCR 空白归一化。' if i==21 else '第 '+str(i)+' 段普通正文。'),'pages':[2] if i==21 else []} for i in range((page-1)*20+1,min(page*20,21)+1)]
            return httpx.Response(200,json={'references':refs,'total':21,'has_more':page==1,'page':page})
        if doc_id not in rows:return None
        item=rows[doc_id]
        if action=='outline':return httpx.Response(200,json={'entries':[]})
        headers={'X-Watermark-Trace':item['trace']}
        if action=='page':
            number=int(parse_qs(parsed.query).get('page',['1'])[0]);name=item['pages'][number-1]
            headers.update({'Content-Type':'image/png','X-Document-Pages':str(len(item['pages']))})
        elif action=='thumbnail':name=item['thumbnail'];headers['Content-Type']='image/png'
        else:name=item['original'];headers['Content-Type']=item['mime']
        return httpx.Response(200,content=(args.formats_dir/name).read_bytes(),headers=headers)

    def check(page,state,experience,args,temp,errors):
        base=page.url.rstrip('/')
        page.goto(base+'/full')
        page.get_by_role('tab',name='资料库',exact=True).click()
        row=page.locator('.ckb-project-directory').filter(has_text=library['name'])
        expect(row).to_be_visible()
        # Physical double-click on the row itself, including blank space.
        row.dblclick(position={'x':15,'y':35})
        expect(page.get_by_role('heading',name=library['name'],exact=True)).to_be_visible()
        card=page.locator('.ckb-subfolder-card').filter(has_text='子目录验证')
        expect(card).to_be_visible();card.dblclick(position={'x':15,'y':40})
        expect(page.get_by_role('button',name='项目空间',exact=True)).to_be_visible()
        def upload_ui(name):
            file=temp/name;file.write_text('FIRST_MARKER 正文 LAST_MARKER',encoding='utf-8')
            page.get_by_role('button',name='上传文件',exact=True).click()
            page.locator('input[aria-label=选择上传资料]').set_input_files(str(file))
            page.get_by_role('button',name='上传并归档',exact=True).click()
            done=page.get_by_role('button',name='完成，查看资料',exact=True)
            expect(done).to_be_visible(timeout=20000);done.click()
            with state.db() as db:return db.scalar(select(CompanyDocument.id).where(CompanyDocument.title==name))
        first=upload_ui('第一份.txt')
        with state.db() as db:
            d=db.get(CompanyDocument,first);d.state='ready';d.cloud_id='first';db.commit()
        second=upload_ui('第二份.txt')
        expect(page.locator('[data-document-id="'+first+'"]')).to_be_visible()
        expect(page.locator('[data-document-id="'+second+'"]')).to_be_visible()
        page.screenshot(path=str(args.output_dir/'continuous-upload.png'),animations='disabled')
        # Selection controls must not open the reader; body double-click must.
        first_card=page.locator('[data-document-id="'+first+'"]')
        first_card.locator('input[type=checkbox]').dblclick(force=True)
        expect(page.locator('.ckb-reader-dialog:visible')).to_have_count(0)
        first_card.dblclick(position={'x':12,'y':160})
        reader=page.locator('.ckb-reader-dialog:visible');expect(reader).to_be_visible()
        expect(reader.locator('.ckb-fulltext-document')).to_contain_text('LAST_MARKER',timeout=15000)
        reader.get_by_role('textbox',name='搜索解析文字').fill('末页关键词')
        reader.get_by_role('button',name='查找',exact=True).click()
        expect(reader.locator('.ckb-source-reader')).to_contain_text('已检查全部可用解析片段',timeout=15000)
        expect(reader.locator('.ckb-source-reader mark')).to_have_count(1)
        expect(reader.locator('.ckb-source-reader')).to_contain_text('21 / 21')
        page.screenshot(path=str(args.output_dir/'parsed-search-last-page.png'),animations='disabled')
        reader.locator('.el-dialog__headerbtn').click()
        # An experience file has its own cancel/confirm delete entry.
        response=upload(state,b'experience text',name='独立删除文件.txt',project_id=experience['id'])
        file_id=response.json()['id']
        with state.db() as db:
            d=db.get(CompanyDocument,file_id);d.state='ready';d.cloud_id='experience';db.commit()
        page.reload();page.get_by_role('tab',name='经验沉淀',exact=True).click()
        page.locator('.ckb-project-directory').filter(has_text=experience['name']).dblclick(position={'x':15,'y':35})
        card=page.locator('.ckb-case-card').filter(has_text='独立删除文件.txt')
        expect(card).to_be_visible();card.get_by_role('button',name='删除资料：独立删除文件.txt',exact=True).click()
        box=page.locator('.el-message-box:visible');expect(box).to_contain_text('独立删除文件.txt')
        box.get_by_role('button',name='取消',exact=True).click();expect(card).to_be_visible()
        card.get_by_role('button',name='删除资料：独立删除文件.txt',exact=True).click();box.get_by_role('button',name='删除',exact=True).click()
        expect(card).to_have_count(0,timeout=15000)
        assert state.client.get('/company-knowledge/documents/'+file_id+'/original').status_code==404
        # A saved nonempty note also has its own delete entry in the editor.
        page.get_by_role('button',name='新建图文笔记',exact=True).click()
        page.get_by_role('textbox',name='笔记标题').fill('独立删除笔记')
        page.get_by_role('textbox',name='笔记正文').fill('这是一篇需要单独删除的非空笔记。')
        page.get_by_role('button',name='保存',exact=True).click()
        expect(page.locator('.kn-save-status')).to_contain_text('草稿已保存',timeout=20000)
        with state.db() as db:
            from company_notes import CompanyNote
            note_id=db.scalar(select(CompanyNote.id).where(CompanyNote.title=='独立删除笔记'))
        page.get_by_role('button',name='删除笔记',exact=True).click()
        expect(box).to_contain_text('独立删除笔记');box.get_by_role('button',name='取消',exact=True).click()
        expect(page.get_by_role('textbox',name='笔记正文')).to_contain_text('非空笔记')
        page.get_by_role('button',name='删除笔记',exact=True).click()
        # The rich-note confirmation deliberately names the note and affected versions.
        box.get_by_role('button',name='确认删除笔记',exact=True).click()
        expect(page.locator('.kn-dialog:visible')).to_have_count(0,timeout=15000)
        assert state.client.get('/company-knowledge/notes/'+note_id).status_code==404
        decoded=[]
        if formats:
            page.get_by_role('tab',name='资料库',exact=True).click()
            page.locator('.ckb-project-directory').filter(has_text='19 类格式实际显示验证').dblclick(position={'x':15,'y':35})
            # Drive the real component method to cover all pages independent of catalogue pagination.
            for doc_id,item in rows.items():
                fmt=item['format'];print('Browser decode '+fmt,flush=True)
                page.evaluate('id=>{const c=window.app.$refs.knowledge;c.openDocument(c.documents.find(d=>d.id===id));}',doc_id)
                expect(reader).to_be_visible()
                expect(reader.locator('.el-dialog__title')).to_have_text('matrix.'+fmt.lower())
                if item['pages']:
                    page.wait_for_function('()=>{const i=document.querySelector(".ckb-reader-dialog .ckb-pdf-sheet img");return i?.complete&&i.naturalWidth>100;}')
                    control=reader.get_by_role('spinbutton',name='跳转到页码');control.fill(str(len(item['pages'])));control.press('Enter')
                    page.wait_for_function('n=>{const i=[...document.querySelectorAll(".ckb-reader-dialog .ckb-pdf-sheet")].find(s=>Number(s.dataset.page)===n)?.querySelector("img");return i?.complete&&i.naturalWidth>100;}',arg=len(item['pages']))
                elif fmt in {'TXT','MD'}:expect(reader.locator('.ckb-fulltext-document')).to_contain_text('LAST_MARKER')
                elif fmt in {'PNG','JPG','JPEG'}:page.wait_for_function('()=>{const i=document.querySelector(".ckb-original-pane>img");return i?.complete&&i.naturalWidth===360;}')
                else:page.wait_for_function('()=>{const m=document.querySelector(".ckb-media-reader audio,.ckb-media-reader video");return m?.readyState>=1&&Number.isFinite(m.duration)&&m.duration>=1;}')
                page.screenshot(path=str(args.output_dir/('format-'+fmt.lower()+'.png')),animations='disabled')
                decoded.append(fmt);reader.locator('.el-dialog__headerbtn').click()
                expect(reader).to_have_count(0)
        assert not errors,errors
        result={'status':'passed','checks':['physical project/folder/file double-click','control clicks ignored','two sequential uploads without reload','ready and pending both visible','search all 21 fragments including last page','OCR whitespace highlighting','experience file cancel/delete','nonempty note cancel/delete'],'browser_decoded_formats':decoded,'console_errors':errors}
        (args.output_dir/'result.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
        print(json.dumps(result,ensure_ascii=False))
    return {'response':response,'check':check}
